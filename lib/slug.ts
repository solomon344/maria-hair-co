/**
 * Turns any text into a URL slug: "Mariéa's Hydrating Shampoo!" → "marieas-hydrating-shampoo".
 * Accents are stripped so URLs stay plain ASCII.
 */
export function slugify(input: string): string {
  return input
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80)
    .replace(/-+$/g, "");
}
